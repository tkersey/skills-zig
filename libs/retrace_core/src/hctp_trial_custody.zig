fn object(value: std.json.Value) !std.json.ObjectMap {
    return switch (value) {
        .object => |map| map,
        else => error.ObjectRequired,
    };
}

fn array(value: std.json.Value) !std.json.Array {
    return switch (value) {
        .array => |items| items,
        else => error.ArrayRequired,
    };
}

fn string(value: std.json.Value) ![]const u8 {
    return switch (value) {
        .string => |text| text,
        else => error.StringRequired,
    };
}

fn boolean(value: std.json.Value) !bool {
    return switch (value) {
        .bool => |flag| flag,
        else => error.BooleanRequired,
    };
}

fn required(map: std.json.ObjectMap, key: []const u8) !std.json.Value {
    return map.get(key) orelse error.RequiredFieldMissing;
}

fn requiredObject(map: std.json.ObjectMap, key: []const u8) !std.json.ObjectMap {
    return object(try required(map, key));
}

fn requiredArray(map: std.json.ObjectMap, key: []const u8) !std.json.Array {
    return array(try required(map, key));
}

fn requiredString(map: std.json.ObjectMap, key: []const u8) ![]const u8 {
    return string(try required(map, key));
}

fn requireExactKeys(map: std.json.ObjectMap, expected: []const []const u8) !void {
    if (map.count() != expected.len) return error.CustodyShapeInvalid;
    for (expected) |key| _ = map.get(key) orelse return error.CustodyShapeInvalid;
}

fn validateFingerprint(value: []const u8) !void {
    if (value.len != "sha256:".len + 64 or !std.mem.startsWith(u8, value, "sha256:")) {
        return error.FingerprintInvalid;
    }
    for (value["sha256:".len..]) |byte| {
        if (!std.ascii.isDigit(byte) and !(byte >= 'a' and byte <= 'f')) {
            return error.FingerprintInvalid;
        }
    }
}

fn validateLowerHexNonce(value: []const u8, expected_len: usize) !void {
    if (value.len != expected_len) return error.CustodyNonceInvalid;
    for (value) |byte| {
        if (!std.ascii.isDigit(byte) and !(byte >= 'a' and byte <= 'f')) {
            return error.CustodyNonceInvalid;
        }
    }
}

/// The arm-map opening retains the 16-byte nonce generated by the v1 trial
/// compiler, encoded as exactly 32 bare lowercase hexadecimal characters.
pub fn validateArmMapNonce(value: []const u8) !void {
    return validateLowerHexNonce(value, 32);
}

/// Every nonce generated specifically for `hylo-trial-custody/v1` is a full
/// SHA-256 digest encoded as exactly 64 bare lowercase hexadecimal characters.
pub fn validateNonce(value: []const u8) !void {
    return validateLowerHexNonce(value, 64);
}

pub fn digestValueAlloc(allocator: std.mem.Allocator, value: std.json.Value) ![]u8 {
    return canonical_json.digestValueAlloc(allocator, value);
}

pub fn treatmentCommitmentAlloc(
    allocator: std.mem.Allocator,
    treatment: std.json.ObjectMap,
) ![]u8 {
    var out: std.Io.Writer.Allocating = .init(allocator);
    defer out.deinit();
    try out.writer.writeAll("{\"arm_id\":");
    try canonical_json.writeCanonicalString(&out.writer, try requiredString(treatment, "arm_id"));
    try out.writer.writeAll(",\"materialization_fingerprint\":");
    try canonical_json.writeCanonicalString(
        &out.writer,
        try requiredString(treatment, "materialization_fingerprint"),
    );
    try out.writer.writeAll(",\"materialization_ref\":");
    try canonical_json.writeCanonicalString(
        &out.writer,
        try requiredString(treatment, "materialization_ref"),
    );
    try out.writer.writeAll(",\"nonce\":");
    try canonical_json.writeCanonicalString(&out.writer, try requiredString(treatment, "nonce"));
    try out.writer.writeAll(
        ",\"schema\":\"hylo-treatment-materialization-opening/v1\"," ++
            "\"value_fingerprint\":",
    );
    try canonical_json.writeCanonicalString(
        &out.writer,
        try requiredString(treatment, "value_fingerprint"),
    );
    try out.writer.writeByte('}');
    return canonical_json.digestBytesAlloc(allocator, out.written());
}

